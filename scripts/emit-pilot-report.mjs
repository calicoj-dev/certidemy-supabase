/**
 * emit-pilot-report.mjs -- turn PILOT-GROUNDED-<CERT>.json into the markdown report, in
 * AUDIT-SAMPLE.md's layout, with `key_support` shown.
 *
 * READ-ONLY. It reads the artifact the generator persisted and formats it. It does NOT
 * generate, re-gate or re-solve: the items in the report are byte-for-byte the items that
 * were measured, which is the whole reason the generator persists before it reports.
 *
 * ============ EVERY NUMBER HERE IS COMPUTED FROM THE ARTIFACT ============
 *
 * A hand-transcribed table in this repository has already dropped a row. The counts, the
 * per-gate rejection tallies and the survivor list are derived, and the emitter refuses to
 * write if its own totals do not reconcile against the artifact's.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, "..");
let IN = "PILOT-GROUNDED-AIMSF.json", OUT = null;
for (const a of process.argv.slice(2)) {
  let m;
  if ((m = /^--in=(.+)$/.exec(a))) { IN = m[1]; continue; }
  if ((m = /^--out=(.+)$/.exec(a))) { OUT = m[1]; continue; }
  console.error("unknown flag " + JSON.stringify(a) + " -- READ-ONLY; flags are --in= and --out=");
  process.exitCode = 2; process.exit();
}
const j = JSON.parse(readFileSync(join(ROOT, IN), "utf8"));
OUT = OUT || IN.replace(/\.json$/, ".md");

const items = j.items || [];
const survivors = items.filter((r) => r.verdict === "survivor");
const byCode = items.filter((r) => r.verdict === "rejected by code");
const bySolver = items.filter((r) => r.verdict === "rejected by solver");
const undecided = items.filter((r) => r.verdict === "solver could not run");

/* Reconcile before writing. If these disagree the artifact and the report would tell two
 * stories and the report is the one that gets quoted. */
if (survivors.length + byCode.length + bySolver.length + undecided.length !== items.length) {
  console.error("REFUSING TO WRITE: verdicts do not partition the items (" +
    items.length + " items, " + (survivors.length + byCode.length + bySolver.length + undecided.length) + " classified)");
  process.exitCode = 2; process.exit();
}
if (typeof j.survivors === "number" && j.survivors !== survivors.length) {
  console.error("REFUSING TO WRITE: the artifact says " + j.survivors + " survivors and the items say " + survivors.length);
  process.exitCode = 2; process.exit();
}

const L = (s) => md.push(s);
const md = [];
L("# Grounded generator pilot -- " + j.certification);
L("");
L("**Section 4 of the grounded-generator brief. Measured, not asserted.** Generated by");
L("`scripts/gen-grounded-items.mjs` against `" + j.standard + ":" + j.edition + "` and formatted by");
L("`scripts/emit-pilot-report.mjs` from `" + IN + "`. Nothing in the live bank was touched: this");
L("was a dry run, and the artifact is what `--apply --from=` would insert item for item.");
L("");
L("## What the numbers are");
L("");
L("| | |");
L("|---|---|");
L("| model | `" + j.model + "` |");
L("| items attempted | " + j.attempted + ", allocated across the domains by `weight_pct` |");
L("| items the writer produced | " + j.generated + " |");
L("| **survivors** | **" + survivors.length + "** |");
L("| rejected by a code gate | " + byCode.length + " |");
L("| rejected by the blind solver | " + bySolver.length + " |");
L("| undecided (solver could not run) | " + undecided.length + " |");
L("| tasks mapped to passages | " + j.tasks_mapped + " of " + j.tasks_total + " |");
L("");
if (j.generation_note) {
  L("");
  L("**How these items came to exist.** " + j.generation_note);
}
L("");
L("Allocation is by domain weight rather than evenly over tasks, because that is the basis");
L("`generate-mock-exam` assembles a form on. A pilot spread evenly would over-sample the");
L("light domains and say nothing about the shape of a real form.");
L("");
L("## Why items were rejected");
L("");
L("A single item can fail more than one gate, so these do not sum to the rejection count.");
L("");
L("| n | gate |");
L("|---|---|");
/* THE OPTIONS PROBE NEVER REJECTS, SO IT DOES NOT BELONG IN A REJECTION TABLE.
 * The director's correction. It appeared here at 18 -- the largest row in the table -- for a
 * check that by design only flags, which read as the single biggest cause of rejection while
 * rejecting nothing at all. Its count is reported in its own section. */
for (const [k, n] of Object.entries(j.reject_counts || {}).sort((a, b) => b[1] - a[1])) {
  if (/^options probe/i.test(k)) continue;
  L("| " + n + " | " + k + " |");
}
L("");
L("**The options-only probe is not in this table.** It flags; it never rejects. Listing it here");
L("made a check that rejects nothing look like the largest cause of rejection. Its count is in");
L("its own section below.");
L("");
L("**`solver COULD NOT RUN` is not a rejection and is never counted as one.** A step that");
L("could not start is not a step that failed: folding it into the rejections would blame the");
L("items for the transport, and folding it into the survivors would clear items nobody checked.");
L("");
L("## The gates, and which of them is not a model");
L("");
L("| gate | what it checks | model involved |");
L("|---|---|---|");
L("| `clause-exists` | every clause named is in the library, and is not a declared library gap | no |");
L("| `verbatim` | `key_support` occurs **exactly** in the named passage | no |");
L("| `modal-fidelity` | a `must` claim needs a `shall` anchor in a `shall` clause | no |");
L("| `superseded-wording` | retired edition wording anywhere in the item | no |");
L("| `structure` | cue guard, key-as-longest, odd-one-out by negation and by opening word | no |");
L("| `near-duplicate` | share of the **shorter** stem's distinctive terms against live items on the same task | no |");
L("| `shared-distractor-phrase` | a run of 4+ words every distractor carries and the key does not | no |");
L("| `anchor-is-primary` | the key anchors in a **primary** passage of the task, not a supporting one | no |");
L("| `reproduction` | at most a 9-word run shared with any source, in any **served** field | no |");
L("| blind solver | is it solvable to the key from the passages, with no second defensible option | **yes, and it never sees the key** |");
L("| options-only probe | could a candidate with no knowledge pick the key from the option shapes | **yes, and it sees only the options** |");
L("");
L("The three gates below the line are new in this run, and each answers a defect the director");
L("found by reading the first pilot:");
L("");
L("- **`anchor-is-primary`** takes out the off-task items. Two of the first pilot's survivors");
L("  anchored in a real clause, verbatim, at the right modal strength -- and the clause was not");
L("  what the task examines. Every gate that existed passed them.");
L("- **`shared-distractor-phrase`** takes out the giveaway: three distractors ending in the same");
L("  clause that the stem excludes.");
L("- **`reproduction`** is the gap the first pilot had no gate for at all.");
L("");
/* ---------------------------------------------------------------- the ruled additions */
if (j.paraphrase_retry) {
  L("## The paraphrase retry");
  L("");
  L("| | |");
  L("|---|---|");
  L("| reproduction failures given one retry | " + ((j.paraphrase_retry.fixed || 0) + (j.paraphrase_retry.still_failing || 0)) + " |");
  L("| **fixed on retry** | **" + (j.paraphrase_retry.fixed || 0) + "** |");
  L("| still failing after retry | " + (j.paraphrase_retry.still_failing || 0) + " |");
  L("");
  L("The retry is offered for REPRODUCTION ONLY. It is the one failure a rewrite can fix without");
  L("changing what the item measures: the claim, the key and the anchor all stay and only our");
  L("wording moves. A modal error or a wrong anchor is a different item, so neither is retried.");
  L("The offending run is named in the retry -- \"paraphrase this\" without it rewrites around the");
  L("wrong span -- and the result is RE-GATED, never trusted.");
  L("");
}

{
  const runs = survivors.map((r) => r.longest_served_run).filter((x) => typeof x === "number");
  L("## Reproduction in served fields");
  L("");
  L("| | |");
  L("|---|---|");
  L("| ceiling, stem and options | a run of at most **9** words shared with any source |");
  L("| ceiling, explanation | 9 words unquoted, plus ONE attributed quotation of at most one sentence |");
  L("| longest served run, max across survivors | " + (runs.length ? Math.max(...runs) : "n/a") + " |");
  L("| median | " + (runs.length ? runs.slice().sort((a, b) => a - b)[Math.floor(runs.length / 2)] : "n/a") + " |");
  L("| **survivors over the ceiling** | **" + runs.filter((x) => x > 9).length + "** |");
  L("");
  L("The first pilot had no such gate and **17 of its 31 survivors carried a run of 10 words or");
  L("more**, the worst 20. The generator reproduces the standard because it is handed the");
  L("standard, which is the cost of grounding and the reason this gate is not optional here.");
  L("");
  L("The runs are measured with the lesson scanner's own tokenisation -- one implementation. The");
  L("quotation allowance is a MODE in that module, not a copy. `key_support` is exempt because it");
  L("is never served.");
  L("");
  L("**And the index is wider than the library.** The scanner holds nine documents, including");
  L("ISO/IEC 22989, 27000, 27004 and 27005, which the task map does not use. One rejection in this");
  L("run is a 16-word run against **22989:2022** -- a standard no passage was supplied from, so the");
  L("item reproduced it from recall while writing about something else. Scoring against the wider");
  L("index is deliberate: the ceiling is about what a candidate can recognise, and recognition does");
  L("not care which document we happened to map.");
  L("");
}

if (j.anchor_clusters) {
  L("## Anchor clusters -- flagged, not rejected");
  L("");
  if (!j.anchor_clusters.length) {
    L("_None: no two survivors in different tasks anchor in the same clause._");
  } else {
    L("Items in **different tasks** whose keys rest on the **same clause**. A candidate who reads");
    L("one learns the answer to the others, and stem identity cannot see it -- their stems differ,");
    L("which is exactly why the deployed dedupe misses them.");
    L("");
    L("| clause | survivors | tasks |");
    L("|---|---|---|");
    for (const c of j.anchor_clusters) L("| " + c.family + " | " + c.items + " | " + c.tasks.join(", ") + " |");
    L("");
    L("Recorded per item as `grounding_family`. **`generate-mock-exam` is not touched**, by");
    L("instruction; migration 376 adds the column so the assembler can dedupe on it if you rule that way.");
  }
  L("");
}

{
  const flags = items.filter((r) => r.options_probe && r.options_probe.state === "flag");
  const unrun = items.filter((r) => r.options_probe && r.options_probe.state === "could-not-run");
  L("## The options-only probe");
  L("");
  L("A third model call on the survivors, seeing the four option texts and **nothing else** -- no");
  L("stem, no passages, no key. It flags an item a candidate with zero knowledge could answer from");
  L("the shape of the options. It never rejects: with four options it is right one time in four by");
  L("luck, so a flag needs both the key AND a concrete, checkable cue.");
  L("");
  L("| | |");
  L("|---|---|");
  L("| survivors probed | " + survivors.length + " |");
  L("| **flagged** | **" + flags.length + "** |");
  L("| probe could not run | " + unrun.length + " |");
  L("");
  if (flags.length && survivors.length && flags.length / survivors.length > 0.4) {
    L("> **THIS RATE IS A DESIGN ERROR IN THE REPORT, NOT " + flags.length + " FINDINGS.** " +
      Math.round(100 * flags.length / survivors.length) + " percent of survivors");
    L("> flagged. This repository's own rule is that a guard firing on the normal case gets deleted");
    L("> by the first person it inconveniences, and that a firing count above a stated threshold is");
    L("> a design error rather than a backlog of fixes. So the members were read before the number");
    L("> was reported.");
    L("");
    const qual = flags.filter((r) => /absolute|restrictive|qualifier|exhaustive|excuse|justif/i.test(r.options_probe.cue || ""));
    L("> **AND READING THEM FOUND ONE PATTERN, NOT " + flags.length + ".** " + qual.length + " of the " + flags.length +
      " cues describe the same thing:");
    L("> the generator makes a distractor wrong by ADDING AN ABSOLUTE OR RESTRICTIVE QUALIFIER, or a");
    L("> self-justifying \"because...\" clause, and leaves the key as the plain statement. That is one");
    L("> habit of the writer prompt, and it is exploitable without knowing the subject.");
    L("");
    L("> **The remedy is the one you ruled: rewrite the cue out.** Not a harder gate, not trickery,");
    L("> not a longer stem. It belongs in the writer prompt -- tell it not to manufacture a wrong");
    L("> answer by qualifying a right one -- and that is a change to what the generator ACCEPTS, so");
    L("> it is not made here. The remaining " + (flags.length - qual.length) + " cues are parallelism and length, listed below.");
    L("");
  }
  if (flags.length) {
    L("| task | cue kind | the cue, as the probe stated it |");
    L("|---|---|---|");
    for (const r of flags) {
      L("| " + r.task_code + " | `" + r.options_probe.cue_kind + "` | " +
        String(r.options_probe.cue).replace(/\|/g, "/").replace(/\s+/g, " ").slice(0, 190) + " |");
    }
    L("");
  }
}

L("---");
L("");
L("## Survivors");
L("");
L("Each shows the anchor the item points at. **`key_support` is internal**: it is a sentence");
L("copied out of a licensed standard as the evidence that the item is supported, and it is");
L("never shown to a candidate, returned by a function, or served through MCP.");
L("");

let n = 0;
for (const r of survivors) {
  n++;
  const ki = r.item.options.findIndex((o) => o.is_correct);
  L("### " + n + ". " + j.certification + " · " + (r.domain || "?") + " · task " + r.task_code);
  L("");
  L("**" + r.item.question_text + "**");
  L("");
  r.item.options.forEach((o, i) => {
    const letter = String.fromCharCode(97 + i);
    L(i === ki ? "- **`KEY` " + letter + ") " + o.text + "**" : "- " + letter + ") " + o.text);
  });
  L("");
  L("*explanation:* " + (r.item.explanation || "_none_"));
  L("");
  L("*`key_support` — " + j.standard + " clause " + r.item.key_support_clause + ":*");
  L("");
  L("> " + String(r.item.key_support).replace(/\s+/g, " ").trim());
  L("");
  const solverNote = r.solver && r.solver.raw && r.solver.raw.answer_reason;
  L("*blind solver:* answered " + String.fromCharCode(65 + ki) + ", no second defensible option" +
    (solverNote ? " — " + String(solverNote).replace(/\s+/g, " ").trim() : ""));
  L("");
  const gl = (r.gates || []).map((g) => g.id + " " + (g.pass === true ? "pass" : g.pass === false ? "FAIL" : "unasserted") +
    " (" + g.examined + ")").join(" · ");
  L("*gates:* " + gl);
  L("");
  L("*longest served run:* " + (typeof r.longest_served_run === "number" ? r.longest_served_run + " words" + (r.longest_served_in ? " in the " + r.longest_served_in : "") : "not measured") +
    "  (ceiling 9)" + (r.attributed_quotation ? "  plus one " + r.attributed_quotation.words + "-word attributed quotation in the " + r.attributed_quotation.field : "") +
    "   *anchor family:* " + (r.grounding_family || "none") +
    (r.options_probe && r.options_probe.state === "flag" ? "   **OPTIONS-PROBE FLAG (" + r.options_probe.cue_kind + ")**" : ""));
  L("");
}
if (!survivors.length) L("_No item survived every gate._");

L("---");
L("");
L("## Rejected, with the reason");
L("");
L("Kept in full rather than counted. An over-refusing gate produces findings that look like");
L("rigour and nobody investigates a refusal, so the refusals are the half of this report");
L("that needs reading.");
L("");
for (const r of [...byCode, ...bySolver, ...undecided]) {
  const ki = r.item.options.findIndex((o) => o.is_correct);
  L("### " + j.certification + " · task " + r.task_code + " — " + r.verdict);
  L("");
  L("**" + r.item.question_text + "**");
  L("");
  r.item.options.forEach((o, i) => {
    const letter = String.fromCharCode(97 + i);
    L(i === ki ? "- **`KEY` " + letter + ") " + o.text + "**" : "- " + letter + ") " + o.text);
  });
  L("");
  if (r.item.key_support_clause) {
    L("*claimed anchor — clause " + r.item.key_support_clause + ":* " +
      (r.item.key_support ? "`" + String(r.item.key_support).replace(/\s+/g, " ").trim().slice(0, 220) + "`" : "_none_"));
    L("");
  }
  for (const g of (r.gates || []).filter((x) => x.pass === false || x.pass === null)) {
    L("- **" + g.id + "** " + (g.pass === null ? "unasserted" : "FAIL") + ": " + g.reason);
  }
  if (r.solver && r.solver.state !== "accepted") L("- **blind solver** " + r.solver.state + ": " + r.solver.reason);
  L("");
}

L("---");
L("");
L("## What this pilot does not show");
L("");
L("- **Tier A and Tier B rates are a HUMAN READ, and this report is not one.** The target was");
L("  zero Tier A and a Tier B rate well under 9%. Nothing here can claim either: a Tier A");
L("  finding is a wrong key, and the instrument that establishes a key is wrong is somebody");
L("  reading the item against the standard. What the gates establish is narrower and worth");
L("  saying exactly: every survivor points at a real sentence in a pinned edition, the");
L("  sentence says what the item claims it says at the strength the item claims, and a model");
L("  that never saw the key reached the key from the passages alone.");
L("- **A DEFINITION CLAUSE'S `normative` CLASS IS THE WEAKEST THING IN THE LIBRARY.** The");
L("  extractor classes a passage by the strongest modal in its own text, which is right for a");
L("  requirement clause and crude for a terms-and-definitions entry: a definition whose note");
L("  contains the word *can* is classed `can`, and a definition imposes nothing at all. One");
L("  rejection in this run turns on that (clause 3.2). Refusing is still the right direction --");
L("  an item may not say *should* on the authority of a definition -- but the class is a proxy");
L("  and `informative` would describe those rows better.");
L("- **The near-duplicate gate compares stems.** Two items with different stems and the same");
L("  answer are invisible to it -- which is exactly the eight near-duplicate pairs the");
L("  480-item audit found by reading. A threshold cannot find those.");
L("- **A dry run of a generator is a sample, not a preview.** A second run writes different");
L("  items. These are the items that were gated, because the artifact was persisted first.");
L("- **The library is PARTIAL where it says so.** " +
  ((j.reject_counts && Object.keys(j.reject_counts).some((k) => /clause-exists/.test(k)))
    ? "Items were refused for naming a clause the library does not hold; that is the gate working."
    : "No item was refused for naming a missing clause in this run."));
L("");
L("## The comparison the decision actually needs");
L("");
L("This report cannot be read against the old generator on its own. The old path's error rate");
L("is known from a human read -- 16 wrong keys in 822 items, 1.9% -- and the equivalent number");
L("for these survivors requires the same instrument: somebody reading them against ISO/IEC");
L("42001:2023. The survivors above are laid out in `AUDIT-SAMPLE.md`'s format so that read can");
L("happen the same way, and each one carries the sentence it rests on so the reading is against");
L("the standard's own words rather than against recall.");

writeFileSync(join(ROOT, OUT), md.join("\n") + "\n", "utf8");
console.log("wrote " + OUT + "  (" + survivors.length + " survivors, " +
  (byCode.length + bySolver.length + undecided.length) + " not cleared, every count derived from " + IN + ")");
