/**
 * item-disposition.mjs -- which artifact survivors are still AWAITING, and which are already dealt with.
 *
 * ONE implementation, because two instruments now need the same answer and they must not disagree:
 *
 *   report-aimsf-completion   "how many items would reach a floor on approval"
 *   anchor-cap-census         "how full are this task's clauses, counting items awaiting a read"
 *
 * The second is new (PROMPT-97 addendum s1). Had it computed its own answer, a survivor counted as pending by
 * one and disposed by the other would make the cap and the completion report contradict each other about the
 * same item -- and this repository's own rule is that a computation with a stated invariant has exactly one
 * implementation.
 *
 * ============ FIVE WAYS AN ARTIFACT SURVIVOR STOPS AWAITING, EACH DERIVED ============
 *
 *   INSERTED       its stem is in the bank. The caller supplies that set, because only it holds a credential
 *   REJECTED       the standing rejections file, unioned with each artifact's own `rejected` block
 *   SUPERSEDED     an id named as `revision_of` by a later revision -- its replacement is a different item
 *   GATE-REFUSED   a non-survivor verdict in any artifact
 *   WITHDRAWN      a whole artifact declared superseded, with a reason, in AIMSF-ARTIFACT-DISPOSITIONS.json
 *
 * THE FIFTH IS DECLARED AND THE OTHER FOUR ARE DERIVED, AND THAT ASYMMETRY IS THE POINT. A probe artifact
 * regenerated by a fuller run leaves no trace anywhere: its items are not rejected, nothing supersedes them by
 * id, and the gates passed them. Only the person who launched the second run knows the first was a
 * measurement. That is a fact about an intention, so it is written down once with its reason, exactly as a
 * director's rejection is -- and **nothing is disposed for being old**, because "probably superseded by now"
 * is the assumption that produced the task 1.2 case.
 *
 * APPEND, NEVER OVERWRITE. An item can be both gate-refused and rejected by ruling; those are different facts
 * and the record that survives should carry both.
 */
import { readFileSync, existsSync, readdirSync } from "node:fs";
import { join } from "node:path";
import { itemIdOfStem } from "./item-id.mjs";

const readJson = (p) => JSON.parse(readFileSync(p, "utf8"));

/**
 * Every generator artifact in the root, found BY SHAPE rather than by a name pattern.
 *
 * A name list goes stale the moment a run is named something new, and this repository records that defect for
 * `anchor-layers.mjs`. An artifact is a JSON object with an `items` array whose entries carry `item_id` and
 * `verdict` -- which no report, shortfall or census file does.
 */
export function generatorArtifacts(root) {
  const out = [];
  for (const f of readdirSync(root)) {
    if (!f.endsWith(".json")) continue;
    if (!/^(AIMSF|PILOT)/.test(f)) continue;
    if (/-raw\.json$/.test(f)) continue;        /* the raw writer output is pre-gate: no verdicts to read */
    let j;
    try { j = readJson(join(root, f)); } catch { continue; }
    if (!j || !Array.isArray(j.items) || !j.items.length) continue;
    const first = j.items[0];
    if (!first || typeof first.item_id !== "string" || typeof first.verdict !== "string") continue;
    out.push(f);
  }
  return out.sort();
}

/**
 * @param root        repository root
 * @param opts.insertedStems  Set of item ids (stem hashes) already in the bank. REQUIRED: omitting it would
 *                            silently treat every inserted item as awaiting, which is the double-count that
 *                            makes a cap refuse correct generation.
 * @returns { disposed, awaiting, artifacts, withdrawn, counts }
 *          disposed  Map id8 -> reason
 *          awaiting  [{ id, task, clause, file, stem }] survivors with no disposition
 */
export function resolveDispositions(root, { insertedStems, inject } = {}) {
  if (!(insertedStems instanceof Set)) {
    throw new Error("resolveDispositions: insertedStems is required. Without it every inserted item counts " +
      "as awaiting and the cap double-counts.");
  }
  const disposed = new Map();
  const dispose = (id, why) => {
    const k = String(id).slice(0, 8);
    disposed.set(k, disposed.has(k) ? disposed.get(k) + "  ||  " + why : why);
  };

  /* `inject` replaces the filesystem for controls ONLY. A control that had to write real artifacts into the
   * repository root to test this would be a control nobody runs. */
  const src = inject || null;

  /* ---- WITHDRAWN: whole artifacts declared superseded ---- */
  const withdrawn = new Map();          /* file -> reason */
  const declared = src ? (src.dispositions || {}) : (existsSync(join(root, "AIMSF-ARTIFACT-DISPOSITIONS.json"))
    ? readJson(join(root, "AIMSF-ARTIFACT-DISPOSITIONS.json")) : {});
  for (const w of (declared.withdrawn || [])) {
    if (w && w.file && w.why) withdrawn.set(w.file, w.why);
  }

  /* ---- the standing rejection list ---- */
  const standing = src ? (src.rejections || {}) : (existsSync(join(root, "AIMSF-DIRECTOR-REJECTIONS.json"))
    ? readJson(join(root, "AIMSF-DIRECTOR-REJECTIONS.json")) : {});
  for (const r of (standing.rejections || [])) {
    if (r && r.id) dispose(r.id, "REJECTED by ruling (" + (r.ruled || "?") + "): " + (r.why || ""));
  }

  /* ---- per-artifact: reject blocks, revisions, and gate verdicts ---- */
  const artifacts = src ? Object.keys(src.artifacts || {}).sort() : generatorArtifacts(root);
  const survivors = [];
  for (const f of artifacts) {
    const j = src ? src.artifacts[f] : readJson(join(root, f));
    for (const r of (j.rejected || [])) if (r && r.id) dispose(r.id, "REJECTED in " + f + ": " + (r.why || ""));
    for (const r of j.items) {
      if (r.revision_of) dispose(r.revision_of, "SUPERSEDED by a revision in " + f);
      if (r.verdict !== "survivor") { dispose(r.item_id, "GATE-REFUSED in " + f); continue; }
      survivors.push({ id: String(r.item_id), file: f, task: r.task_code,
        clause: (r.item || {}).key_support_clause, stem: (r.item || {}).question_text });
    }
  }
  /* WITHDRAWN is applied to survivors after the scan, so a withdrawn artifact's items are disposed even though
   * their verdict is `survivor` and nothing else names them. */
  for (const s of survivors) {
    if (withdrawn.has(s.file)) dispose(s.id, "WITHDRAWN: " + withdrawn.get(s.file));
  }

  /* ============ RESERVED: ACCEPTED, HELD, AND NOT OCCUPYING CAP SPACE ============
   *
   * Ruled PROMPT-97 addendum s2 for `fc0000a0`: *"Hold as a reserve (not inserted, not rejected)... record it
   * with verdict `accept`... The insert must skip it while the cap is full."*
   *
   * It is a SIXTH state and it collapses into neither neighbour. AWAITING would fill its clause and refuse an
   * item the director accepted on that same clause -- measured: A.10.3 for task 3.4 reads 3 against a cap of 2,
   * and one of the three is the reserve. REJECTED would record a good item as wrong.
   *
   * So it is disposed for counting and its verdict is `accept`. The reason travels, because an exclusion whose
   * ground is not recorded is indistinguishable from an omission. */
  const reserved = new Map();
  for (const r of (declared.reserved || [])) {
    if (r && r.id) reserved.set(String(r.id).slice(0, 8), r);
  }
  for (const [id, r] of reserved) {
    dispose(id, "RESERVED (verdict " + (r.verdict || "accept") + "): " + (r.note || "held"));
  }

  /* ---- what is left ---- */
  const awaiting = [];
  const counts = { survivors: survivors.length, inserted: 0, disposed: 0, awaiting: 0 };
  const seen = new Set();
  for (const s of survivors) {
    /* the same item can appear in several artifacts (a probe and an insert set), so it is counted once */
    if (seen.has(s.id)) continue;
    seen.add(s.id);
    if (insertedStems.has(s.id) || insertedStems.has(itemIdOfStem(s.stem))) { counts.inserted++; continue; }
    if (disposed.has(s.id.slice(0, 8))) { counts.disposed++; continue; }
    awaiting.push(s);
  }
  counts.awaiting = awaiting.length;
  counts.reserved = reserved.size;
  return { disposed, awaiting, artifacts, withdrawn, reserved, counts };
}

/**
 * Controls, on injected artifacts. The headline case is the one the director found: two runs drawing the same
 * task before either is inserted.
 */
export function itemDispositionControls() {
  const cases = [];
  const ok = (what, pass, detail = "") => cases.push({ what, pass, detail });
  const item = (id, task, clause, stem, verdict = "survivor") =>
    ({ item_id: id, task_code: task, verdict, item: { question_text: stem, key_support_clause: clause } });
  const run = (root, inject, inserted = []) =>
    resolveDispositions(root, { insertedStems: new Set(inserted), inject });

  /* ============ THE 1.2 CASE, REPRODUCED ============
   *
   * Two runs, each two items on A.3.2 and two on A.10.2, neither inserted. Before this module the census saw
   * the first run's four as absent and the second run was told its clauses were empty. The control asserts the
   * count a cap would now be applied against, per clause -- which is the number that was wrong, not the fact
   * that some items exist. */
  {
    const r = run("/nowhere", { artifacts: {
      "RUN-A.json": { items: [
        item("aaaa0001", "1.2", "A.3.2", "A1"), item("aaaa0002", "1.2", "A.3.2", "A2"),
        item("aaaa0003", "1.2", "A.10.2", "A3"), item("aaaa0004", "1.2", "A.10.2", "A4")] },
      "RUN-B.json": { items: [
        item("bbbb0001", "1.2", "A.3.2", "B1"), item("bbbb0002", "1.2", "A.3.2", "B2"),
        item("bbbb0003", "1.2", "A.10.2", "B3"), item("bbbb0004", "1.2", "A.10.2", "B4")] },
    } });
    const per = {};
    for (const a of r.awaiting) per[a.clause] = (per[a.clause] || 0) + 1;
    ok("the 1.2 case: two runs on one task give EIGHT awaiting items on two clauses",
      r.awaiting.length === 8 && per["A.3.2"] === 4 && per["A.10.2"] === 4, JSON.stringify(per));
    /* AND THE DIRECTION THAT MATTERS: with a cap of 2, four on a clause is over it. Asserted here rather than
     * left to the caller, because "the census can see them" and "the cap refuses them" are different claims
     * and only the second is the thing that was broken. */
    ok("...and a cap of 2 is exceeded on both clauses",
      Object.values(per).every((n) => n > 2), JSON.stringify(per));
  }

  /* ---- an INSERTED item is not awaiting, and is not double-counted ---- */
  {
    const stem = "already in the bank";
    const r = run("/nowhere", { artifacts: { "RUN-A.json": { items: [item("cccc0001", "1.2", "A.3.2", stem)] } } },
      [itemIdOfStem(stem)]);
    ok("an inserted survivor is not awaiting", r.awaiting.length === 0 && r.counts.inserted === 1,
      JSON.stringify(r.counts));
  }

  /* ---- a REJECTED item is not awaiting, from either source ---- */
  {
    const a = { artifacts: { "RUN-A.json": { items: [item("dddd0001", "1.2", "A.3.2", "x")] } },
      rejections: { rejections: [{ id: "dddd0001", ruled: "PROMPT-x", why: "surplus" }] } };
    ok("a survivor on the standing rejection list is not awaiting", run("/nowhere", a).awaiting.length === 0);
    const b = { artifacts: { "RUN-A.json": {
      items: [item("eeee0001", "1.2", "A.3.2", "x")], rejected: [{ id: "eeee0001", why: "surplus" }] } } };
    ok("a survivor in an artifact's own reject block is not awaiting", run("/nowhere", b).awaiting.length === 0);
  }

  /* ---- RESERVED: accepted, held, and out of the awaiting count ---- */
  {
    const inj = { artifacts: { "RUN-A.json": { items: [
      item("9999aaaa", "3.4", "A.10.3", "the reserve"), item("9999bbbb", "3.4", "A.10.3", "the accepted one")] } },
      dispositions: { reserved: [{ id: "9999aaaa", verdict: "accept", note: "reserve: over cap" }] } };
    const r = run("/nowhere", inj);
    ok("a reserved item is not awaiting, so it cannot fill its own clause",
      r.awaiting.length === 1 && r.awaiting[0].id === "9999bbbb", JSON.stringify(r.counts));
    ok("...and its ACCEPT verdict and note are recorded, not just its exclusion",
      /RESERVED \(verdict accept\)/.test(r.disposed.get("9999aaaa") || "") &&
      /over cap/.test(r.disposed.get("9999aaaa") || ""), r.disposed.get("9999aaaa") || "(none)");
    /* THE DIRECTION THAT MATTERS: without this, the accepted sibling on the same clause would be the second of
     * two awaiting items and a cap of 2 would leave it no room at insert. */
    const per = {};
    for (const a of r.awaiting) per[a.clause] = (per[a.clause] || 0) + 1;
    ok("...leaving room under a cap of 2 for the accepted sibling", per["A.10.3"] === 1, JSON.stringify(per));
  }

  /* ---- a WITHDRAWN artifact's survivors are not awaiting, and the reason travels ---- */
  {
    const inj = { artifacts: { "PROBE.json": { items: [item("ffff0001", "1.2", "A.3.2", "x")] } },
      dispositions: { withdrawn: [{ file: "PROBE.json", why: "a ceiling measurement" }] } };
    const r = run("/nowhere", inj);
    ok("a withdrawn artifact's survivors are not awaiting", r.awaiting.length === 0, JSON.stringify(r.counts));
    ok("...and the withdrawal reason is recorded, not just the exclusion",
      /ceiling measurement/.test(r.disposed.get("ffff0001") || ""), r.disposed.get("ffff0001") || "(none)");
  }

  /* ---- NOT withdrawn for being old: an undeclared artifact stays awaiting ---- */
  {
    const r = run("/nowhere", { artifacts: { "OLD-RUN.json": { items: [item("aaaa9999", "1.2", "A.3.2", "x")] } } });
    ok("an artifact with no disposition stays AWAITING however old", r.awaiting.length === 1);
  }

  /* ---- a non-survivor is never awaiting ---- */
  {
    const r = run("/nowhere", { artifacts: { "RUN-A.json": {
      items: [item("aaaa8888", "1.2", "A.3.2", "x", "rejected by code")] } } });
    ok("a gate-refused item is not awaiting", r.awaiting.length === 0 &&
      /GATE-REFUSED/.test(r.disposed.get("aaaa8888") || ""), r.disposed.get("aaaa8888") || "(none)");
  }

  /* ---- the same item in two artifacts is counted ONCE ---- */
  {
    const r = run("/nowhere", { artifacts: {
      "RUN-A.json": { items: [item("aaaa7777", "1.2", "A.3.2", "same stem")] },
      "RUN-B.json": { items: [item("aaaa7777", "1.2", "A.3.2", "same stem")] } } });
    ok("an item appearing in two artifacts is counted once", r.awaiting.length === 1,
      JSON.stringify(r.counts));
  }

  /* ---- APPEND, NEVER OVERWRITE: two reasons for one id both survive ---- */
  {
    const inj = { artifacts: { "RUN-A.json": {
      items: [item("aaaa6666", "1.2", "A.3.2", "x", "rejected by code")] } },
      rejections: { rejections: [{ id: "aaaa6666", ruled: "PROMPT-x", why: "and by ruling" }] } };
    const why = run("/nowhere", inj).disposed.get("aaaa6666") || "";
    ok("an item both gate-refused and rejected carries both reasons",
      /GATE-REFUSED/.test(why) && /by ruling/.test(why), why);
  }

  /* ---- insertedStems is REQUIRED, because omitting it silently double-counts ---- */
  {
    let threw = false;
    try { resolveDispositions("/nowhere", { inject: { artifacts: {} } }); } catch { threw = true; }
    ok("omitting insertedStems throws rather than defaulting to empty", threw);
  }

  return { cases, allPass: cases.every((c) => c.pass) };
}
