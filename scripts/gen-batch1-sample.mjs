#!/usr/bin/env node
/**
 * gen-batch1-sample.mjs -- render the batch-1 paired sample from the spec.
 *
 * READ-ONLY apart from the markdown it writes. No flags.
 *
 * A FILE, not a `node -e`, because the output carries backticks and a backtick
 * inside a double-quoted shell argument is command substitution.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const b = JSON.parse(readFileSync(join(ROOT, "BATCH1-RETRANSLATION.json"), "utf8"));
const F = "```";
const o = [];
const words = (s) => s.trim().split(/\s+/).filter(Boolean).length;

o.push("# Batch 1 retranslation -- paired sample, before it is applied", "");
o.push("The AIMS-F batch-1 lessons and their AIMS-IA pair: English that moved when the batch-1");
o.push("rewrites landed, translations that never followed.", "");
o.push("Generated by `" + b.generator + "` with `" + b.model + "`. **These are the exact bytes");
o.push("`--from` will write.** The generator is not deterministic, so the reviewed artifact and");
o.push("the written artifact are the same object by construction.", "");
o.push("**Nothing has been written to the database.**", "");

o.push("## READ THIS FIRST: two of these blocks translate a BROKEN English sentence", "");
o.push("`01-03-the-ai-system-life-cycle` block 14. The batch-1 rewrite's `from` anchor began with");
o.push("the word `assessments`, which was the tail of *risk assessments and impact assessments*.");
o.push("Replacing it ate the second noun and stranded the modifier:", "");
o.push("```");
o.push("... run risk assessments and impact Clause 8.2 sets two independent triggers ...");
o.push("```", "");
o.push("**That English is SERVED and has been since 2026-09-23.** The retranslation renders the");
o.push("orphan as a VERB in both languages -- *ejecutan evaluaciones de riesgo e impactan*,");
o.push("*executam avaliacoes de risco e impactam* -- which is fluent and says something the");
o.push("English never did.", "");
o.push("Every gate passed it, correctly: they compare a translation against its English, and here");
o.push("the ENGLISH is what is wrong. **Do not apply those two blocks until the English is");
o.push("repaired.** The other 28 are unaffected.", "");
o.push("Checked across every declared span replacement: `check-rewrite-seams.mjs`, invariant 12.");
o.push("18 splices located, **one break**, this one. Two anchors no longer resolve in the live");
o.push("English and are reported rather than assumed clean.", "");

o.push("## What is here, and what is not", "");
o.push("| | |");
o.push("|---|---|");
o.push("| blocks | " + b.rows.length + " across " + new Set(b.rows.map((r) => r.slug)).size + " lessons |");
o.push("| retried after a gate refusal | " + b.rows.filter((r) => r.retried).length +
  " -- the other " + b.rows.filter((r) => !r.retried).length + " are byte-identical to the first emit |");
o.push("| unit | the BLOCK containing a declared English edit, not the whole body |");
o.push("");
o.push("The unit is a block because these bodies average 13,000 characters and the English moved");
o.push("in a handful of declared spans. Retranslating whole bodies would have replaced roughly");
o.push("234,000 characters of text that is fine, and every regenerated word is an unreviewed word.", "");
o.push("**`05-01-aims-monitoring-and-measurement` is excluded.** Its ENGLISH is withheld for ISO");
o.push("reproduction at 12 words, so regenerating its translations would faithfully translate a");
o.push("reproduction. It is blocked on the English repair, not on this batch.", "");
o.push("**Two lessons could not be located and are not here**: `isms-ia-01-01-audit-parties`, whose");
o.push("declared anchor matches no block in the current English, and `aims-ia-01-01-who-commissioned-it`,");
o.push("whose anchor matches two. Both are reported rather than guessed at.", "");

const bySlug = new Map();
for (const r of b.rows) {
  if (!bySlug.has(r.slug)) bySlug.set(r.slug, new Map());
  const byBlock = bySlug.get(r.slug);
  if (!byBlock.has(r.block_index)) byBlock.set(r.block_index, {});
  byBlock.get(r.block_index)[r.language] = r;
}

let n = 0;
for (const [slug, byBlock] of [...bySlug.entries()].sort()) {
  o.push("---", "", "## `" + slug + "`", "");
  for (const [idx, langs] of [...byBlock.entries()].sort((a, c) => a[0] - c[0])) {
    const es = langs["es-419"], pt = langs["pt-BR"];
    const any = es || pt;
    n++;
    o.push("### " + n + ". block " + idx +
      ((es && es.retried) || (pt && pt.retried) ? "  — RETRIED after a gate refusal" : ""));
    o.push("");
    o.push("**EN** (the rewritten English this block now carries)");
    o.push("", F, any.english_source, F, "");
    for (const [label, r] of [["es-419", es], ["pt-BR", pt]]) {
      if (!r) { o.push("**" + label + "** — not in this batch", ""); continue; }
      o.push("**" + label + "** — replaces " + words(r.from_block) + " words with " + words(r.to_block));
      o.push("");
      o.push("<details><summary>what it replaces (renders the OLD English)</summary>");
      o.push("", F, r.from_block, F, "</details>", "");
      o.push(F, r.to_block, F, "");
    }
  }
}

o.push("---", "", "## Gates every block passed", "");
o.push("- **A** sentence-level modal alignment, guidance severity (these are ISO certifications)");
o.push("- **B** defined-term collapse: available/retained, extent/scope, effectiveness");
o.push("- **C** register, against the certification's own dominant register (both are `usted`)");
o.push("- **D** clause vocabulary — REPORTED, never gating, per the ruling that 574 corpus-wide is");
o.push("  a consistency measure and a mechanical sweep would hit correct uses");
o.push("- accent, through the declared classes at floor 3");
o.push("- the model-refusal pattern, which caught two blocks in the first emit");
o.push("");
o.push("The three retried blocks failed on: a model refusal (twice) and an `available -> retained`");
o.push("crossing carrying three missing accents. **All three missing accents traced to my own");
o.push("prompt**, which wrote the register note ASCII-only and got `Secao`, `disponivel` and");
o.push("`extensao` back. The note is accented now.", "");

writeFileSync(join(ROOT, "BATCH1-SAMPLE.md"), o.join("\n"), "utf8");
console.log("wrote BATCH1-SAMPLE.md -- " + n + " block groups, " + b.rows.length + " rows");
