#!/usr/bin/env node
/**
 * READ-ONLY. Writes <SLUG>-SPOTREAD.md for the director: the solver-miss keeps and the inflation
 * samples that survived the re-anchor. No model calls.
 *
 * GITIGNORED: the inflation section prints the anchor phrase the gate judged, which is licensed
 * passage text. Licensed text stays out of git, enforced by content (check-licensed-text).
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { requireKey, getAll } from "./_pg.mjs";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, "..");
let CERT = "ISMS-F", N_MISS = 10, N_INF = 8;
for (const a of process.argv.slice(2)) {
  let m = a.match(/^--cert=(.+)$/);
  if (m) { CERT = m[1]; continue; }
  m = a.match(/^--miss=(\d+)$/);
  if (m) { N_MISS = Number(m[1]); continue; }
  m = a.match(/^--inflation=(\d+)$/);
  if (m) { N_INF = Number(m[1]); continue; }
  console.error("Unrecognised flag: " + a + ". Known: --cert=, --miss=, --inflation=. READ-ONLY.");
  process.exit(2);
}
const SLUG = CERT.replace(/-/g, "");
const merged = new Map();
for (const f of ["-all-secure.json", "-all-secure-rerun.json"]) {
  const p = join(ROOT, "ANCHOR-OR-FLAG-" + CERT + f);
  if (existsSync(p)) for (const it of (JSON.parse(readFileSync(p, "utf8")).items || [])) merged.set(it.prefix, it);
}
const surv = JSON.parse(readFileSync(join(ROOT, SLUG + "-SURVIVORS.json"), "utf8"));
const keep = new Set(surv.keep_ids || []), drop = new Set(surv.drop_ids || []);

const KEY = requireKey(HERE);
const cert = (await getAll(KEY, "certifications?select=id&code=eq." + CERT))[0];
const rows = await getAll(KEY, "quiz_questions?select=id,question_text,options,correct_answer,task_id" +
  "&certification_id=eq." + cert.id + "&language=eq.en&order=id");
const tasks = await getAll(KEY, "tasks?select=id,code,statement&order=code");
const tc = new Map(tasks.map((t) => [t.id, t.code]));
const ts = new Map(tasks.map((t) => [t.id, t.statement]));

const L = [];
L.push("# " + CERT + ": items for the director's spot-read");
L.push("");
L.push("Generated by `scripts/emit-spotread.mjs`. Gitignored: the inflation section quotes anchor text.");
L.push("");

const itemBlock = (it, { withAnchor }) => {
  const r = rows.find((x) => String(x.id).startsWith(it.prefix));
  if (!r) { L.push("- `" + it.prefix + "` no live row"); return; }
  const keyId = (r.correct_answer || [])[0];
  L.push("### `" + it.prefix + "` — task " + tc.get(r.task_id));
  L.push("");
  L.push("*" + String(ts.get(r.task_id) || "").replace(/\s+/g, " ") + "*");
  L.push("");
  L.push(String(r.question_text).replace(/\s+/g, " "));
  L.push("");
  for (const o of r.options || []) {
    L.push("- " + (o.id === keyId ? "**" + o.id + " (key)** " : o.id + ". ") +
      String(o.text).replace(/\s+/g, " "));
  }
  if (withAnchor) {
    const g = (it.gates || []).find((x) => x.id === "modal-fidelity");
    L.push("");
    L.push("- anchor clause: `" + ((it.anchor && it.anchor.clause) || "?") + "`");
    L.push("- the gate's reason: " + String((g && g.reason) || "").replace(/\s+/g, " "));
    if (it.anchor && it.anchor.support) {
      L.push("- the anchor phrase it judged: \"" +
        String(it.anchor.support).replace(/\s+/g, " ").slice(0, 300) + "\"");
    }
  }
  L.push("");
};

/* ---- the solver-miss keeps: stem, options and key ONLY, as ruled ---- */
const miss = [...merged.values()].filter((it) => it.state === "anchored" && keep.has(it.prefix) &&
  ((it.solver && it.solver.state) || "") !== "accepted").slice(0, N_MISS);
L.push("## Solver-miss keeps (" + miss.length + ")");
L.push("");
L.push("Anchored cleanly; the blind solver did not pick the key. Kept and tagged per PROMPT-112 s2.");
L.push("If one of these is really ambiguous, it drops.");
L.push("");
for (const it of miss) itemBlock(it, { withAnchor: false });

/* ---- the inflation drops that SURVIVED the re-anchor ---- */
const inf = [...merged.values()].filter((it) => {
  const g = (it.gates || []).filter((x) => x.pass === false).map((x) => x.id);
  return g.length === 1 && g[0] === "modal-fidelity" && drop.has(it.prefix);
}).slice(0, N_INF);
L.push("## Inflation drops that survived the re-anchor (" + inf.length + ")");
L.push("");
L.push("These have no held normative twin, so the requirement claim is not licensed by numbering.");
L.push("Each one is either a real inflation or an anchor nobody can re-home.");
L.push("");
for (const it of inf) itemBlock(it, { withAnchor: true });

const out = join(ROOT, SLUG + "-SPOTREAD.md");
writeFileSync(out, L.join("\n") + "\n");
console.log("wrote " + out.split(/[\\/]/).pop() + "   solver-miss " + miss.length + ", inflation " + inf.length);
